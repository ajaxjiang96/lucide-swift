import Foundation

/// A single benchmark result row.
struct BenchmarkRow: Sendable {
    let dimension: String
    let lucideSwift: String
    let lucideIconsSwift: String
    let note: String?
}

/// Formats benchmark results as a markdown report.
enum ReportFormatter {

    static func generate(rows: [BenchmarkRow]) -> String {
        let date = ISO8601DateFormatter().string(from: Date())
        let osVersion = ProcessInfo.processInfo.operatingSystemVersionString
        let swiftVersion = "5.9"

        var report = """
        # LucideSwift Benchmark Report

        **Date**: \(date) | **OS**: \(osVersion) | **Swift**: \(swiftVersion)

        > Comparing LucideSwift (code-generated SwiftUI `Shape`) with
        > [lucide-icons-swift](https://github.com/JakubMazur/lucide-icons-swift) (PDF asset catalog via `NSImage`).
        > *Lower is better in all dimensions.*

        ## Results

        | Dimension | LucideSwift (Shape) | lucide-icons-swift (Assets) |
        |---|---|---|

        """

        for row in rows {
            report += "| \(row.dimension) | \(row.lucideSwift) | \(row.lucideIconsSwift) |\n"
        }

        report += """

        ## Notes

        """

        let notes = rows.compactMap { row -> String? in
            guard let note = row.note else { return nil }
            return "- **\(row.dimension)**: \(note)"
        }

        if notes.isEmpty {
            report += "*No additional notes.*\n"
        } else {
            for note in notes {
                report += "\(note)\n"
            }
        }

        report += """

        ---
        *Generated by [LucideBenchmark](https://github.com/ajaxjiang96/lucide-swift/tree/main/Benchmarks)*
        """

        return report
    }

    // MARK: - Formatting Helpers

    static func formatBytes(_ bytes: UInt64) -> String {
        if bytes >= 1_000_000_000 {
            return String(format: "%.2f GB", Double(bytes) / 1_000_000_000)
        } else if bytes >= 1_000_000 {
            return String(format: "%.2f MB", Double(bytes) / 1_000_000)
        } else if bytes >= 1_000 {
            return String(format: "%.1f KB", Double(bytes) / 1_000)
        }
        return "\(bytes) B"
    }

    static func formatTime(_ seconds: Double) -> String {
        if seconds < 0.000_001 {
            return String(format: "%.2f ns", seconds * 1_000_000_000)
        } else if seconds < 0.001 {
            return String(format: "%.2f µs", seconds * 1_000_000)
        } else if seconds < 1.0 {
            return String(format: "%.2f ms", seconds * 1_000)
        }
        return String(format: "%.2f s", seconds)
    }
}
